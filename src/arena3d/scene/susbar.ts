/**
 * 의심도 막대의 **색** — 머리 위 눈금이 어느 칸에 있는가 (WorldScene 의 RemoteAvatar 가 쓴다).
 *
 * 2026-09-02 사용자: "의심도 바 색 바꿀 수 있나? 잘 안 보여" · "바 색을 바꿔야 할 거 같은데".
 *
 * 여태 색은 둘뿐이었다 — 평상시 호박(#e2b07f), 뜨거우면 옅은 분홍(#ff9f9f). 둘 다 이 홀의
 * 밝은 청회색 벽 앞에서 물이 빠졌고, 무엇보다 **뜨거운 쪽이 평상시보다 연했다.** 방을 훑다가
 * "누가 타고 있나"를 알려면 길이를 재는 게 아니라 **색이 튀어야** 한다.
 *
 * 세 칸으로 나눈다. 칸을 가르는 것은 판이 쥔 눈금 하나뿐이다(BALANCE.hotAt) — 그 선을 넘으면
 * 자동 시행이 처형판으로 서므로, 색이 바뀌는 자리와 판이 바뀌는 자리가 같아야 읽힌다.
 * 그 절반이 중간 칸의 시작이다: 한 번 어긋나면(+34) 대개 여기 들어온다.
 *
 * 규칙만 떼어 놓은 이유는 화면에서 눈으로 잡기 어려워서다 — 개체를 폐기선까지 태우려면
 * 판을 여러 번 돌려야 하는데, 그 사이에 색이 한 칸 어긋나 있어도 알아채기 어렵다.
 */
export type SusLevel = 'calm' | 'warm' | 'hot';

/** 눈금 하나(0~100)가 어느 칸인가. hotAt 은 판의 처형판 문턱을 그대로 받는다 */
export function susLevel(sus: number, hotAt: number): SusLevel {
  if (sus >= hotAt) return 'hot';
  return sus >= hotAt / 2 ? 'warm' : 'calm';
}

/**
 * 칸마다의 색과 빛.
 * 붉은 칸에만 빛을 얹는다 — 방 건너에서도 **그 몸 하나가 먼저 눈에 들어야** 한다.
 * 셋 다 이 화면이 이미 쓰는 색이다 (features/arena 의 --ok · --warn · --danger 를 한 칸씩 올린 것).
 */
export const SUS_LOOK: Record<SusLevel, { fill: string; glow: string }> = {
  calm: { fill: '#6fe3a6', glow: 'none' },
  warm: { fill: '#ffc061', glow: 'none' },
  hot: { fill: '#ff4d4d', glow: '0 0 9px rgba(255,70,70,0.95)' },
};

