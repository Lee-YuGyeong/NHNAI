/** 제자리 섞기 — 이름·성격을 뽑는 쪽이 전부 이걸 쓴다 (이야기로 들어온 판의 이름표도: arena/handover 의 buildStoryCast) */
export function shuffle<T>(arr: T[]): T[] {
  for (let i = arr.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/** 이름 풀에서 무작위로 n 개 — 성격과 이름의 짝이 매판 바뀌게 하는 쪽이 쓴다 (/lab·/arena 공용) */
export function sampleNames(n: number): string[] {
  return shuffle([...NAMES]).slice(0, n);
}

