/**
 * 페르소나 — 이 게임에서 제일 많이 만지게 될 파일.
 *
 * ★ 전제: **여기 있는 전원이 사람처럼 말한다.**
 *   서로를 번호가 아니라 **이름**으로 부른다. 번호로 부르는 순간 사람 대화가 아니게 된다.
 *   2098년의 AI 는 사람 말투를 완벽히 흉내 낸다. 그래서 "기계 같은 말투"는 단서가 되지 않는다.
 *   AI 를 로봇처럼 말하게 만들면 사람만 혼자 어색해져서 판이 1분 만에 끝난다.
 *   갈리는 지점은 말투가 아니라 **기억·일관성·반응 속도·아는 척**이다.
 *
 * 노드 6개 중 다섯은 AI, 하나는 사람이다. **사람에게도 위장 페르소나가 배정된다** —
 * 그 성격을 흉내 내는 것이 사람 쪽 플레이의 전부다.
 *
 * 모델은 성능으로만 고른다 (말투 차이로 쓰지 않는다). 리더만 opus, 나머지는 sonnet —
 * haiku 는 구독 경로(CLI)에서 15~25초씩 걸려 대화가 끊긴다.
 *
 * 페르소나를 쓸 때의 기준:
 *  - 개성은 **성격과 말버릇**으로 준다. 존댓말/반말도 섞는다 — 그래야 사람 여섯처럼 보인다.
 *  - 한두 개의 **말버릇**을 준다. 사람이 흉내 낼 수 있어야 재밌다.
 *  - **의심하는 방식**을 각자 다르게 준다. 색출은 여기서 갈린다.
 *  - 금지 사항을 적어 둔다. 안 그러면 전부 친절한 조수처럼 군다.
 *  - **각자에게 결함을 하나씩 준다.** 이게 없으면 AI 다섯이 전부 완벽해서 혼자 헷갈리는 사람이
 *    즉시 드러난다. 단 결함은 **판단의 편향**이지 감정이 아니다 — 감정은 사람만의 것으로 남겨 둔다.
 *    그게 이 게임에서 유일하게 사람을 가르는 선이다.
 */

