/**
 * **리더의 말을 언제까지 기다리는가** — 그 규칙만 떼어 놓은 자리.
 *
 * ArenaFeature 안에 두면 시험할 수가 없다(3300줄 · Three.js 캔버스). 그런데 여기서 틀리면
 * 리더가 말하는 도중에 다음 것이 겹친다 — 화면에서 눈으로 잡기 어려운 종류의 고장이라,
 * 규칙만은 손으로 붙잡아 둔다.
 *
 * 지금 이 규칙을 쓰는 곳은 넷이고, 넷 다 같은 모양이다 (바닥 · 낭독 · 천장):
 *   · 브리핑 → 카운트다운 (briefWaitMs — 판이 지시 도중에 돌지 않게)
 *   · 판독 → 대화        (briefWaitMs)
 *   · 폐기 → 다음 검사   (purgeHoldMs — 선고 위에 검사가 겹치지 않게)
 *   · 결말 → 결말 카드   (endHoldMs — 내 선고 위에 「다시 — 새 판」이 겹치지 않게)
 */

/**
 * ── 리더가 화면을 쥐는 시간의 천장(ms) ──
 *
 * 방송이 도는 동안은 구역 통신 패널이 내려가고(commsHushed) 개체들도 말을 안 올린다 —
 * 안 보이는 패널에 대고 떠들면 그 몇 줄은 아무도 못 본 채로 지나간다.
 *
 * 그 「도는 동안」을 재는 값 둘(`speaking` · 자막이 서 있는가)이 **둘 다 영영 안 꺼질 수
 * 있다**: 합성이 멈추면 speaking 이 참으로 남고, 자막 상자는 그 speaking 을 보고 붙잡는다.
 * 그러면 방이 통째로 멎는다 — 패널은 안 올라오고 아무도 말을 안 한다. 이 파일의 다른 셋과
 * 같은 이유로 천장을 둔다: **방송이 멈춰도 판은 돌아야 한다.**
 *
 * 20초는 이 자리에 오는 방송을 다 덮는다. 판 사이(idle·result)에 나가는 것은 도착 접수 ·
 * 지시 · 판독 · 폐기 선고 · 「첫 검사」뿐이고 전부 60자 안쪽이라, 낭독(글자당 182ms)으로도
 * 11초를 안 넘는다. 지시문처럼 긴 방송은 시행 구간이라 패널이 애초에 안 선다 (TRIAL_PHASES).
 */
export const HUSH_CEIL_MS = 20000;

/**
 * 지금부터 세기 시작할 때까지 남은 시간(ms).
 *
 * 기다리는 기준이 둘이고 **늦은 쪽**을 기다린다:
 * - `floor` 자막이 그 줄을 띄워 두는 시간. 소리가 없어도 눈으로 읽을 시간은 있어야 한다.
 * - 낭독이 끝나는 순간. 길이를 어림하지 않고 `speaking` 이 거짓이 되는 것으로 안다 —
 *   합성 길이는 셀 수 없고, 어림은 경우마다 따로 틀린다 (shared/broadcast 참고).
 *
 * `ceil` 은 낭독이 영영 안 끝날 때를 위한 안전선이다. 방송이 통째로 멈춰도 판은 돌아야 한다.
 *
 * @param speaking 리더가 아직 말하는 중인가 (selectBroadcastSpeaking)
 * @param elapsed  브리핑이 시작된 뒤 지난 시간(ms)
 */
export function briefWaitMs(speaking: boolean, elapsed: number, floor: number, ceil: number): number {
  return Math.max(0, (speaking ? ceil : floor) - elapsed);
}

/**
 * ── 폐기가 화면을 쥐고 있는 동안(ms) — 이만큼은 다음 시행이 안 선다 ──
 *
 * 처형과 시행은 **같은 순간에 발동한다.** 몰이가 개체 하나를 100 까지 태우면 그 갱신 하나로
 * 두 효과가 잇달아 돈다: 앞엣것이 폐기하고(경보 · 조사 결과 방송 · 무대로 걷는 행진),
 * 뒤엣것이 남은 의심도 도합을 세어 새 검사를 세운다. 둘 다 리더의 방송이고, 뒤엣것은
 * 경보(alarm)라 앞엣것을 **끊고 맨 앞에 선다** (shared/broadcast-kind).
 * 그래서 「즉시 폐기」가 중간에 잘리고, 그 위로 카운트다운이 겹쳤다
 * (2026-09-02 사용자: "폐기랑 게임이랑 동시에 나올 때도 있어").
 *
 * 규칙은 브리핑·판독과 같다 — 리더가 말을 마칠 때까지 기다리고, 소리가 없어도 바닥만큼은 든다.
 * 바닥은 방송이 없어도 **폐기가 눈에 끝나야** 하는 시간이다: 선고받은 몸이 그 자리에서
 * 무대 쪽을 돌아보고(PURGE_AIM_MS 0.9초) 넘어져 누운 채로 남았다가 지워진다(PURGE_DOWN_MS 2.2초).
 *
 * 6초에서 4초로 내렸다 (2026-09-03). 6초는 **무대까지 걸어가던 시절**의 값이다 — 홀을 가로지르는
 * 그 걸음이 없어졌으니(features/arena 의 Condemned) 같은 값을 들고 있으면 다 끝난 화면을
 * 3초 더 붙잡는 셈이다. 4초면 마지막 자세가 한 박자 남고 다음 검사가 선다.
 */
export const PURGE_FLOOR_MS = 4_000;
/** 방송이 통째로 멈춰도 판은 돌아야 한다 — 브리핑의 천장과 같은 몫 */
export const PURGE_CEIL_MS = 20_000;

/** 폐기가 난 뒤 지금까지 elapsed 만큼 지났을 때, 다음 시행까지 남은 시간(ms) */
export function purgeHoldMs(speaking: boolean, elapsed: number): number {
  return briefWaitMs(speaking, elapsed, PURGE_FLOOR_MS, PURGE_CEIL_MS);
}

/**
 * ── 결말 카드가 뜨기까지(ms) — **선고를 다 듣고 나서 판이 끝난다** ──
 *
 * 내가 격리되면 리더는 두 문장을 읽는다: 「… AI 반응으로 확정한다. 즉시 격리」와
 * 「조사 결과 — 나는 사람이었다」. 그런데 결말 카드(.endgame)가 격리와 **같은 순간에**
 * 화면을 덮었다 — 리더는 아직 내 죄목을 부르고 있는데 화면은 붉은 판에 「다시 — 새 판」이었다
 * (2026-09-02 사용자: "리더는 말하고 있는데 나는 빨간색으로 다시 시작 떠").
 * 내가 죽는 장면이 채 끝나기도 전에 다음 판 이야기가 먼저 온 셈이다.
 *
 * 규칙은 위 둘과 같다 — 리더가 말을 마칠 때까지 기다리고, 소리가 없어도 바닥만큼은 든다.
 * 바닥이 7초인 것은 그동안 **내가 쓰러지는 것이 보여야** 하기 때문이다 (Collapse — 눈높이가
 * 1.3초에 걸쳐 바닥까지 내려간다. 그 뒤로 방이 어두워지는 데 5초).
 *
 * 다른 것이 하나 있다: 말이 끝나도 **한 박자(END_TAIL_MS) 를 더 둔다.** 위 둘은 다음 것이
 * 이어지는 자리라 곧바로 세도 되지만, 여기서는 마지막 문장의 자막이 사라지는 것까지가 그 장면이다.
 */
export const END_FLOOR_MS = 7_000;
/** 방송이 통째로 멈춰도 판은 끝나야 한다 — 두 문장이라 폐기 여운의 천장보다 넉넉히 잡는다 */
export const END_CEIL_MS = 30_000;
/** 선고가 끝나고 결말이 뜨기까지의 한 박자 */
export const END_TAIL_MS = 1_400;

/** 판이 끝난 뒤 지금까지 elapsed 만큼 지났을 때, 결말 카드가 뜨기까지 남은 시간(ms) */
export function endHoldMs(speaking: boolean, elapsed: number): number {
  return Math.max(END_TAIL_MS, briefWaitMs(speaking, elapsed, END_FLOOR_MS, END_CEIL_MS));
}
