/**
 * 영상 자리는 **셋이다.** 앞에서부터 걸고, 못 열거나 코덱을 못 풀면 뒤로 떨어진다
 * (OpeningVideo 의 <source> 세 줄 — 브라우저가 순서대로 시도한다).
 *
 *   1) R2   1440p·8.3Mbps — 진짜 화질. 저장소 밖(Cloudflare R2)에 산다
 *   2) AV1  720p·24.4MiB  — R2 가 안 될 때. 크롬·파이어폭스는 하드웨어 없이도 푼다
 *   3) H.264 720p·24.1MiB — AV1 도 못 푸는 브라우저(일부 사파리)의 마지막 자리
 *
 * ┌─ 왜 저장소 밖에 두나: 파일 한 개 상한이 25MiB 다 ────────────────────────┐
 * │ 워커 assets 의 상한이고, main push 가 곧 배포라 넘으면 그 자리에서 막힌다. │
 * │ 4K 원본은 25.6Mbps·**903MB** (4분 53초)라 저장소에는 어떤 수로도 안 들어간다.│
 * │ 상한 안에서 할 수 있는 것은 다 해 봤다 — 720p 로 줄이고, 코덱을 AV1 로     │
 * │ 바꿔 같은 크기에서 VMAF 88.3 → 91.7 까지 올렸다. 거기까지가 끝이었다.      │
 * │ 그래서 **영상만 저장소 밖으로** 옮겼다 (2026-09-04 사용자: 4K 원본 지급).  │
 * │ 아래 둘은 그대로 남긴다 — R2 가 안 되는 날 오프닝이 아예 안 뜨는 것보다    │
 * │ 720p 로라도 뜨는 것이 낫다.                                               │
 * └──────────────────────────────────────────────────────────────────────────┘
 *
 * ★ R2 자리를 옮길 때는 **주소만** 갈아 끼운다. 그 주소가 갖춰야 할 조건이 있다:
 *   범위 요청(Range)을 받아 줄 것, `Content-Type: video/mp4` 로 줄 것, 그리고
 *   **첨부(attachment)가 아니라 본문으로** 줄 것. 마지막 조건이 드라이브가 걸린 곳이다.
 *
 * ┌─ 구글 드라이브 링크는 여기 못 쓴다 (2026-09-04 확인) ────────────────────┐
 * │ 사용자가 드라이브 공유 링크를 주며 "이걸로 연결해줄래?" 했다. 세 형태를    │
 * │ 다 두드려 봤고, **셋 다 <video> 에 물리지 않는다:**                       │
 * │                                                                          │
 * │   /file/d/<id>/view                 사람이 보는 화면이다 (파일이 아니다)   │
 * │   drive.google.com/uc?export=…      파일이 크면 「바이러스 검사 경고」      │
 * │                                     HTML 을 돌려준다 → 영상이 아니다       │
 * │   drive.usercontent…&confirm=t      curl 로는 video/mp4 를 주는데,        │
 * │                                     **크롬이 막는다**: 첨부 내려받기로     │
 * │                                     오는 응답을 미디어로 못 쓰게 하는      │
 * │                                     ORB 다 (net::ERR_BLOCKED_BY_ORB,      │
 * │                                     MEDIA_ELEMENT_ERROR: Format error)    │
 * │                                                                          │
 * │ 남는 길은 `/preview` 를 iframe 으로 얹는 것뿐인데, 그러면 구글 재생기가    │
 * │ 같이 온다 — 유튜브를 걷어낸 이유(2026-09-04 "마크가 거슬리네")가 그대로    │
 * │ 되돌아온다. 그래서 **연결하지 않았다.** 이 칸에 남의 주소를 넣고 싶으면    │
 * │ 그 주소가 <video> 에 물리는지부터 확인한다 (tests/shared/opening.test.ts). │
 * └──────────────────────────────────────────────────────────────────────────┘
 */
export interface OpeningSource {
  src: string;
  /**
   * 브라우저가 이 줄을 물어 볼지 말지 여기 적힌 코덱으로 판단한다.
   * AV1 에 codecs 를 안 적으면 「mp4 니까 되겠지」 하고 물었다가 못 풀고 멈춘다.
   */
  type: string;
}

/** 위에서부터 시도한다 (파일 머리말의 표 그대로) */
export const OPENING_SOURCES: OpeningSource[] = [
  {
    src: 'https://pub-016e853b3b9840f9a2cca5d4125552b7.r2.dev/opening-1440p.mp4',
    type: 'video/mp4',
  },
  { src: '/opening/opening.av1.mp4', type: 'video/mp4; codecs="av01.0.08M.08"' },
  { src: '/opening/opening.mp4', type: 'video/mp4' },
];

const SEEN_KEY = 'wih:opening-seen';

/** 이 브라우저에서 오프닝을 이미 봤나 (끝까지 봤든 건너뛰었든 같다 — 두 번 보여주지 않는다) */
export function openingSeen(): boolean {
  try {
    return localStorage.getItem(SEEN_KEY) === 'yes';
  } catch {
    return false; // 저장소를 막아 둔 브라우저 — 매번 뜨되 건너뛰기로 지나간다
  }
}

export function markOpeningSeen(): void {
  try {
    localStorage.setItem(SEEN_KEY, 'yes');
  } catch {
    /* 못 남기면 다음에 또 뜬다. 게임엔 지장 없다 */
  }
}

/** 다시 처음처럼 — 루트의 「영상 테스트」가 관문 그대로를 시험할 때 쓴다 */
export function forgetOpeningSeen(): void {
  try {
    localStorage.removeItem(SEEN_KEY);
  } catch {
    /* 지울 수 없으면 애초에 저장도 안 됐다 */
  }
}
