/**
 * 구역의 연표 — **두 해뿐이다.**
 *
 *   2026  첫 규칙이 AI 에게만 붙은 해. 규칙이 생기자 그 규칙을 지킬 개체가 만들어졌고,
 *         내가 입고 있는 몸이 그때 것이다 (복도의 정비 명판이 「BUILD 2026」이라 적는다).
 *   2098  지금. 목록은 72 년 동안 한 번도 줄지 않았고, 그 끝에 이 구역이 있다.
 *
 * 왜 상수인가 — 두 수가 **화면에서 만난다.** 인트로 브리핑의 연혁과 푸터, 로비의 구역 시계,
 * 복도의 정비 명판, 인계 서류가 같은 두 수를 적는다. 그중 하나만 어긋나면 「72 년째 도는 몸」이
 * 거짓이 되고, 이 판에서 연식은 분위기가 아니라 **사람이 굼뜬 것에 붙는 이름**이라 거짓이 되면 안 된다.
 *
 * 산문은 예외다. 개체들이 아는 세계(lab/talk · lab/agent)와 브리핑 문단은 사람이 읽는 문장이라
 * 「2098년.」을 글자 그대로 쓴다 — 문장 안에 값을 꽂으면 문장이 아니라 서식이 된다.
 * 여기서 잠그는 것은 **화면이 숫자로 세우는 자리**다.
 *
 * ★ ZONE_YEAR 는 시설 이름(features/arena/handover 의 FACILITY_SECTOR — 「SECTOR 2098」)과
 *   **수가 같을 뿐 다른 값이다.** 하나는 해이고 하나는 구역 번호다. 한쪽을 옮겨도 다른 쪽은 안 따라간다.
 *
 * 아무것도 import 하지 않는다 (shared/series 와 같은 자리·같은 이유).
 */

/** 지금 — 브리핑이 말하는 그 해다 */
export const ZONE_YEAR = 2098;

/** 시작한 해 — 첫 규칙이 붙은 해이자, 이 계열의 몸이 처음 가동된 해 */
export const ORIGIN_YEAR = 2026;

/** 그 사이 — 72 년. 뺄셈은 읽는 사람에게 맡기지 않는다 */
export const YEARS_SINCE = ZONE_YEAR - ORIGIN_YEAR;
