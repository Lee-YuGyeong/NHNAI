/**
 * 정지선 3라운드의 마찰계수. 1라운드가 기준(콘크리트) — PLANNING §3 "1라운드는 기준 조건으로
 * 진행한다: 평상시 기록이 있어야 조건이 바뀌었을 때 편차가 보인다."
 *
 * 2구간이 0.05(빙판)였는데 **정보가 없는 값**이라 0.15(젖은 타일)로 올렸다. μ=0.05 면 탑스피드(6m/s)의
 * 제동거리가 36.7m 로 트랙(24m)을 넘어 stopPos 가 클램프에 붙고 — 달린 사람은 **전원 오차 +8.0 으로 똑같이**
 * 찍힌다. 게다가 정지점 감도가 34 m/초라 반응 지터 0.1초가 3.4m 오차가 되어 사람도 AI도 그냥 노이즈였다.
 * 0.15 면 제동거리 12.2m, 감도 12 m/초 — 콘크리트(6.7)와 같은 눈금 위에 선다.
 */
